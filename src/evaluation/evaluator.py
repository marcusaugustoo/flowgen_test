"""
Evaluator: orchestrates evaluation of generated code against benchmark tests.

Uses the HumanEval check_correctness function as the single evaluation
mechanism for both HumanEval tasks and custom tasks. This ensures that
all tasks are evaluated with the same execution engine, sandbox,
timeout handling, and PASS/FAIL determination.
"""

from __future__ import annotations

import logging
import sys
import time
from pathlib import Path
from typing import Any

from src.benchmarks.base import Problem
from src.evaluation.pass_at_1 import compute_pass_at_1

# Import check_correctness from the HumanEval implementation in the project.
# This is THE evaluation engine — there is no second evaluator.
_HUMAN_EVAL_PATH = str(Path(__file__).resolve().parent.parent.parent / "human-eval")
if _HUMAN_EVAL_PATH not in sys.path:
    sys.path.insert(0, _HUMAN_EVAL_PATH)

from human_eval.execution import check_correctness  # noqa: E402

logger = logging.getLogger(__name__)


class Evaluator:
    """
    Evaluates generated code against benchmark tests.

    Uses HumanEval's check_correctness for sandboxed execution.
    Both HumanEval tasks and custom tasks are evaluated by this
    single mechanism.
    """

    def __init__(self, timeout: float = 30.0) -> None:
        self.timeout = timeout

    def _build_problem_dict(self, problem: Problem, code: str) -> tuple[dict, str]:
        """
        Build the problem dict and completion string for check_correctness.

        For HumanEval tasks:
            prompt = function signature + docstring
            completion = the body generated by the model

        For custom tasks (prompt is plain text, not a function signature):
            prompt = "" (empty — code is complete, not a "completion")
            completion = the full generated code

        The test field always contains the HumanEval-format test code:
            def check(candidate): ...

        Note: check_correctness constructs:
            check_program = prompt + completion + "\\n" + test + "\\ncheck(entry_point)"

        If the test code already ends with "check(entry_point)", we need
        to strip it to avoid double invocation, OR we need to ensure
        the test code does NOT already call check() at the end. Our
        convention is that tests.py INCLUDES the final check() call,
        so we need to handle this.

        Actually, looking at the HumanEval source:
            check_program = prompt + completion + "\\n" + test + "\\n" + f"check({entry_point})"

        The original HumanEval test field includes a check() definition but
        the final "check(entry_point)" is appended by check_correctness.
        However, some custom tests might already include the final call.
        We handle both cases by stripping any trailing check() call from
        the test code, since check_correctness will add it.
        """
        test_code = problem.test

        # Strip the trailing check(entry_point) call if present,
        # because check_correctness appends it automatically.
        entry_point = problem.entry_point
        trailing_call = f"check({entry_point})"
        lines = test_code.rstrip().split("\n")

        # Remove trailing empty lines and the check() call
        while lines and not lines[-1].strip():
            lines.pop()
        if lines and lines[-1].strip() == trailing_call:
            lines.pop()

        cleaned_test = "\n".join(lines)

        # Determine if this is a HumanEval-style task (prompt is a function
        # signature) or a custom task (prompt is plain text).
        # Heuristic: HumanEval prompts start with code (import/def),
        # custom task prompts start with natural language.
        prompt_text = problem.prompt.strip()
        is_code_prompt = (
            prompt_text.startswith("from ")
            or prompt_text.startswith("import ")
            or prompt_text.startswith("def ")
            or prompt_text.startswith("class ")
        )

        if is_code_prompt:
            # HumanEval-style: prompt is function signature, code is completion
            problem_dict = {
                "task_id": problem.task_id,
                "prompt": problem.prompt,
                "test": cleaned_test,
                "entry_point": entry_point,
            }
            completion = code
        else:
            # Custom task: code is complete, prompt is just description
            problem_dict = {
                "task_id": problem.task_id,
                "prompt": "",
                "test": cleaned_test,
                "entry_point": entry_point,
            }
            completion = code

        return problem_dict, completion

    def evaluate_single(
        self,
        code: str,
        problem: Problem,
    ) -> dict[str, Any]:
        """
        Evaluate a single generated code against a problem's tests.

        Uses HumanEval's check_correctness for execution and evaluation.

        Args:
            code: The generated Python code.
            problem: The benchmark problem with tests.

        Returns:
            Result dict with 'passed', 'result', 'task_id', etc.
        """
        start_time = time.perf_counter()

        problem_dict, completion = self._build_problem_dict(problem, code)

        # Use HumanEval's check_correctness — the SINGLE evaluator
        he_result = check_correctness(
            problem=problem_dict,
            completion=completion,
            timeout=self.timeout,
        )

        elapsed_ms = (time.perf_counter() - start_time) * 1000

        result: dict[str, Any] = {
            "task_id": problem.task_id,
            "passed": he_result["passed"],
            "result": he_result["result"],
            "entry_point": problem.entry_point,
            "evaluation_time_ms": elapsed_ms,
            "prompt": problem.prompt,
            "evaluation_status": "completed",
        }

        # Classify errors
        if not he_result["passed"]:
            raw_result = he_result["result"]
            if raw_result == "timed out":
                result["evaluation_status"] = "timeout"
                result["error"] = "Execution timed out"
            elif raw_result.startswith("failed:"):
                result["evaluation_status"] = "execution_error"
                result["error"] = raw_result
            else:
                result["evaluation_status"] = "failed"

        logger.info(
            "Evaluated %s: passed=%s (%.1fms)",
            problem.task_id,
            result["passed"],
            elapsed_ms,
        )

        return result

    def evaluate_batch(
        self,
        code_results: list[dict[str, Any]],
        problems: list[Problem],
    ) -> dict[str, Any]:
        """
        Evaluate a batch of generated code against problems.

        Args:
            code_results: List of dicts with 'task_id' and 'code' keys.
            problems: List of Problem objects.

        Returns:
            Summary dict with individual results and Pass@1 score.
        """
        # Build problem lookup
        problem_map = {p.task_id: p for p in problems}

        results = []
        for cr in code_results:
            task_id = cr["task_id"]
            code = cr["code"]

            if task_id not in problem_map:
                logger.warning("Problem %s not found in benchmark", task_id)
                continue

            result = self.evaluate_single(code, problem_map[task_id])
            results.append(result)

        # Compute Pass@1
        pass_at_1 = compute_pass_at_1(results) if results else 0.0

        return {
            "results": results,
            "pass_at_1": pass_at_1,
            "total": len(results),
            "passed": sum(1 for r in results if r["passed"]),
            "failed": sum(1 for r in results if not r["passed"]),
        }
